"""Records CF-container finish-position serving PROCESSING as data in MLflow.

As of 2026-07-12 the finish-position system is Mac-batch-free: every
prediction is generated by the Cloudflare Container via per-race
"focused-full" runs, triggered by running-style completion or an admin
re-trigger (see `apps/finish-position-cron`). This module answers an
infrastructure-facing question that NEITHER `sync_production.py` (was this
served, and was it accurate) NOR `champion_cell_eval.py`/`cell_eval_runs.py`
(how accurate is the champion) already answers: did the container serve
today's card the way it was designed to -- one race at a time, on schedule,
without partial or duplicate writes, covering the full card -- or is it
exhibiting the failure signatures the pre-CF-only serving-latency audit
already catalogued (batch-fallback bursts, post-time races, partial writes)?

Sources (both READ-ONLY, mirroring this package's existing db.py/serve_eval.py
discipline -- see those modules' own docstrings): the racing Neon database's
`race_finish_position_model_predictions` (via `serve_eval.
fetch_fp_prediction_rows`) for WHAT was actually written and WHEN, and the
local PostgreSQL replica's own jvd_ra/nvd_ra race calendar (via `serve_eval.
fetch_races_scheduled`/`fetch_post_times`) for the expected card and each
race's scheduled post time. No new credential/API surface is introduced: a
Cloudflare D1 REST read (the most literal reading of "D1 realtime_race_
sources" as an expected-card source) would need a `CLOUDFLARE_API_TOKEN`
this repo's env files do not carry today, and jvd_ra/nvd_ra's own
`hasso_jikoku` (post time, "HHMM" text) column is already a genuine, more
authoritative "expected card" oracle -- the same one `serve_eval.
fetch_races_scheduled` already uses for `sync_production.py`'s own
coverage-ratio gap detector -- so this module reuses it instead of adding a
second, narrower data source.

Data model: ONE MLflow run per (date, category) in `config.
EXPERIMENT_FP_CF_SERVING`, identified by a `cf_serving_key = "{date}:
{category}"` tag (mirrors `sync_production.SYNC_KEY_TAG`'s own idiom).
Idempotent by UPDATE-IN-PLACE, not by skip-if-exists: this recorder is
explicitly meant to be re-run many times during race hours (see the
`--partial-coverage-threshold`-style monitoring-sibling use case this was
built for), and each call's per-race table and metrics must REPLACE the
previous snapshot, reflecting the container's progress since the last call --
never accumulate duplicate rows the way a naive re-run of an
exactly-once-per-run table logger would. See `_log_race_table`'s own
docstring for the mechanical consequence of this choice (plain overwriting
artifacts, never `client.log_table`'s special JSON-merge semantics).

The per-race table carries one row per (race, model_version) group actually
served that day: `champion_match` (champion / cell-routed variant / other,
via the SAME duplicated classification rule `sync_production.
_classify_served_model_version` already uses -- see that function's own
"Champion-or-variant serving predicate" section for why hand-duplicating this
~10-line rule across sibling modules, rather than importing it, is this
package's established convention), `write_spread_seconds` (max-min
`prediction_generated_at` across the race's own horse rows -- a real,
directly observable partial-write signal, since every horse in one genuine
UPSERT batch shares Postgres's single per-statement `now()` value), and
`rewrite_count` (see `_build_race_rows`'s own docstring for why this is
tracked as a genuine cross-INVOCATION delta against this run's own
previously-logged table, never fabricated from a single snapshot -- a single
UPSERT-keyed snapshot cannot distinguish "written once" from "written twice
and converged to the same final state").

Anomaly counts, all derived purely from `prediction_generated_at` timestamps
plus the post-time oracle (no additional data source): `late_race_count`
(a race's last write landed within 60 minutes of its own post time, or
after it -- the exact "post後着" phenomenon `serving-latency-audit`
documented for the pre-CF-only hybrid), `missing_before_post_count` (a race
with a resolvable post time that has NEVER been served at all, and that
60-minute deadline has already passed as of `now`), `batch_burst_minute_count`
/ `batch_burst_race_count` (the Mac-batch-fallback signature: more than 4
races landing in the same wall-clock minute -- real per-race container runs
take ~27.5 minutes each, so genuine CF serving can never produce this
pattern; only a batch write of many races in one transaction/script run
can), and `partial_write_race_count` (`write_spread_seconds` above threshold).
"""

