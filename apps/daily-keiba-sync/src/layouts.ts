import type { Provider, RecordColumn, RecordLayout, RecordRow } from "./types";

const RECORD_TERMINATOR_BYTES = 2;
const TYPE_BYTES = 2;
const IDENTIFIER = /^[a-z][a-z0-9_]*$/;

const isObject = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

const parseColumn = (value: unknown): RecordColumn => {
  if (!isObject(value) || typeof value.name !== "string" || typeof value.width !== "number")
    throw new Error("Invalid generated record column");
  if (!IDENTIFIER.test(value.name) || !Number.isInteger(value.width) || value.width < 1)
    throw new Error("Invalid generated record column value");
  return { name: value.name, width: value.width };
};

const parseStringArray = (value: unknown): readonly string[] => {
  if (!Array.isArray(value) || value.some((entry) => typeof entry !== "string"))
    throw new Error("Invalid generated primary key");
  const result: string[] = [];
  for (const entry of value) {
    if (!IDENTIFIER.test(entry)) throw new Error("Invalid generated primary key column");
    result.push(entry);
  }
  if (result.length === 0) throw new Error("Generated primary key is empty");
  return result;
};

const parseLayout = (tableName: string, value: unknown): RecordLayout => {
  if (!IDENTIFIER.test(tableName) || !isObject(value) || !Array.isArray(value.columns))
    throw new Error("Invalid generated record layout");
  if (typeof value.recordBytes !== "number" || typeof value.recordType !== "string")
    throw new Error("Invalid generated record layout metadata");
  const columns = value.columns.map(parseColumn);
  const primaryKey = parseStringArray(value.primaryKey);
  const bytes = columns.reduce((total, column) => total + column.width, RECORD_TERMINATOR_BYTES);
  if (bytes !== value.recordBytes || !/^[A-Z0-9]{2}$/.test(value.recordType))
    throw new Error(`Invalid generated byte layout for ${tableName}`);
  return {
    columns,
    primaryKey,
    recordBytes: value.recordBytes,
    recordType: value.recordType,
    tableName,
  };
};

export const validateRecordLayouts = (value: unknown): ReadonlyMap<string, RecordLayout> => {
  if (!isObject(value) || value.formatVersion !== 1 || !isObject(value.tables))
    throw new Error("Invalid generated record layouts");
  const layouts = new Map<string, RecordLayout>();
  for (const [tableName, table] of Object.entries(value.tables)) {
    const layout = parseLayout(tableName, table);
    layouts.set(`${tableName.slice(0, 3)}:${layout.recordType}`, layout);
  }
  return layouts;
};

