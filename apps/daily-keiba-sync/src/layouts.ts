export const optionalLayoutForRecord = (
  provider: Provider,
  bytes: Uint8Array,
): RecordLayout | undefined => {
  if (bytes.length < TYPE_BYTES) throw new Error("Record is shorter than its type prefix");
  const recordType = String.fromCharCode(...bytes.subarray(0, TYPE_BYTES));
  return LAYOUTS.get(`${provider === "jv" ? "jvd" : "nvd"}:${recordType}`);
};

export const layoutForRecord = (provider: Provider, bytes: Uint8Array): RecordLayout => {
  const layout = optionalLayoutForRecord(provider, bytes);
  if (layout === undefined) throw new Error(`Unsupported ${provider.toUpperCase()} record type`);
  return layout;
};

export const parseFixedRecord = (layout: RecordLayout, bytes: Uint8Array): RecordRow => {
  if (bytes.length !== layout.recordBytes)
    throw new Error(`Invalid ${layout.tableName} record length`);
  if (bytes.at(-2) !== 13 || bytes.at(-1) !== 10)
    throw new Error(`Invalid ${layout.tableName} record terminator`);
  const row: Record<string, string> = {};
  let offset = 0;
  for (const column of layout.columns) {
    const end = offset + column.width;
    row[column.name] = decode(bytes.subarray(offset, end), "cp932");
    offset = end;
  }
  return Object.freeze(row);
};

export const rowKey = (layout: RecordLayout, row: RecordRow): string => {
  const values: string[] = [];
  for (const column of layout.primaryKey) {
    const value = row[column];
    if (typeof value !== "string" && typeof value !== "number")
      throw new Error(`Missing primary key column for ${layout.tableName}`);
    values.push(String(value));
  }
  return values.join("\u001f");
};

export const layoutByTable = (tableName: string): RecordLayout => {
  if (tableName === NETKEIBA_TRAINING_LAYOUT.tableName) return NETKEIBA_TRAINING_LAYOUT;
  for (const layout of LAYOUTS.values()) if (layout.tableName === tableName) return layout;
  throw new Error("Unsupported table");
};
